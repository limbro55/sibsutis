#!/bin/bash

# Очистка экрана
echo -e "\033[2J"

#вкл режима псевдографики
echo -e "\033(0"

# верхнюю границу рамки
echo -e "\033[10;5Hlqqqqqqqk"

# боковые границы
for ((i=11; i<=16; i++)); do
    echo -e "\033[$i;5Hx       x"
done

# нижняя граница
echo -e "\033[17;5Hmqqqqqqqj"

# выкл псевдографику
echo -e "\033(B"

# перемещение курсора вниз
echo -e "\033[20;1H"